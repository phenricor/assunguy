# Extracts the prototype's renderer (canvas, sprites, camera, animation, sound, music, landscape) from the
# frozen legacy/prototype/index.html into apps/game/src/legacy/, as ES modules the new interface drives.
# The vendored code stays as it was (Portuguese, unedited); what it needs from the old game logic and screens
# becomes calls into `hooks`, which apps/game/src/view.ts and the interface fill in. Re-run after changing
# the lists below; never edit the output by hand.
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = (ROOT / 'legacy' / 'prototype' / 'index.html').read_text(encoding='utf-8')
OUT = ROOT / 'apps' / 'game' / 'src' / 'legacy'
OUT.mkdir(parents=True, exist_ok=True)

head_end = SRC.find('<script id="gerador">')
gen_end = SRC.find('</script>', head_end)
main_start = SRC.find('<script>', gen_end) + len('<script>')
main_end = SRC.rfind('</script>')
GERADOR = SRC[head_end + len('<script id="gerador">'):gen_end]
MAIN = SRC[main_start:main_end]
HEAD = SRC[:head_end]
LINES = MAIN.split('\n')

# ---- top-level declarations: name -> (first line, last line exclusive), from one declaration to the next
def split_top(s):
    out, depth, cur, q = [], 0, '', None
    for ch in s:
        if q:
            cur += ch
            if ch == q: q = None
            continue
        if ch in '\'"`': q = ch; cur += ch; continue
        if ch in '([{': depth += 1
        if ch in ')]}': depth -= 1
        if ch == ',' and depth == 0: out.append(cur); cur = ''; continue
        cur += ch
    out.append(cur)
    return out

decl = re.compile(r'^(async function|function|const|let|var|class)\s+(\w+)')
starts = []
for i, ln in enumerate(LINES):
    m = decl.match(ln)
    if not m: continue
    names = [m.group(2)]
    if m.group(1) in ('const', 'let', 'var'):
        body = ln[len(m.group(1)) + 1:]
        if ';' in body and not body.rstrip().endswith('{') and not body.lstrip().startswith('{') and not body.lstrip().startswith('['):
            parts = split_top(body.split(';')[0])
            names = [re.match(r'\s*(\w+)', p).group(1) for p in parts if re.match(r'\s*(\w+)\s*(=|$)', p)]
    starts.append((i, names, m.group(1)))
SPANS = {}
KIND = {}
for n, (i, names, kind) in enumerate(starts):
    end = starts[n + 1][0] if n + 1 < len(starts) else len(LINES)
    for nm in names:
        SPANS.setdefault(nm, (i, end)); KIND.setdefault(nm, 'fn' if 'function' in kind or re.match(rf'^(const|let|var)\s+{nm}\s*=\s*(async\s*)?(\([^)]*\)|\w+)\s*=>', LINES[i]) else 'val')

cfg = json.loads((pathlib.Path(__file__).parent / 'render.json').read_text(encoding='utf-8'))
include = set()
for a, b in cfg['ranges']:
    for nm, (i, e) in SPANS.items():
        if a <= i + 1 < b: include.add(nm)
include |= set(cfg.get('names', []))
include -= set(cfg.get('exclude', []))

# keep each span once, in source order
spans = sorted({SPANS[n] for n in include})
code = '\n'.join('\n'.join(LINES[i:e]) for i, e in spans)
for a, b in cfg.get('replace', []):
    if a not in code: sys.exit(f'replace target missing: {a[:60]}')
    code = code.replace(a, b)

# what the vendored code uses but did not bring along: functions become hook calls, values hook getters
defined = {n for n in SPANS if SPANS[n] in set(spans)}
used = set(re.findall(r'(?<![.\w$])([A-Za-z_]\w*)\b', re.sub(r'//[^\n]*', '', code)))
declare = cfg.get('declare', {})
missing = sorted(n for n in used if n in SPANS and n not in defined and n not in declare)
stubs = []
for n in missing:
    if KIND[n] == 'fn': stubs.append(f'function {n}(...a) {{ return hook("{n}")(...a); }}')
    else: stubs.append(f'const {n} = new Proxy({{}}, {{ get: (_, p) => value("{n}")[p], set: (_, p, v) => {{ value("{n}")[p] = v; return true; }} }});')

lets = [n for n in sorted(defined) if re.match(rf'^(let|var)\b', LINES[SPANS[n][0]]) and re.search(rf'\b{n}\b', LINES[SPANS[n][0]])]
fns = sorted(n for n in defined if KIND[n] == 'fn' or re.match(rf'^(async function|function)\s+{n}\b', LINES[SPANS[n][0]]))
consts = sorted(n for n in defined if n not in lets and n not in fns)

out = ['// GENERATED by tools/legacy-render/extract.py from legacy/prototype/index.html. Do not edit.',
       '// The prototype renderer, unchanged; see docs/GAME.md.',
       '/* eslint-disable */',
       '// @ts-nocheck',
       'export const hooks = {};',
       'const warned = new Set();',
       'function hook(n) { const f = hooks[n]; if (typeof f === "function") return f; if (!warned.has(n)) { warned.add(n); console.warn("legacy hook missing:", n); } return () => undefined; }',
       'function SHEET(n) { return (hooks.SHEETS || {})[n] || n; }',
       'function value(n) { const v = hooks[n]; if (v === undefined && !warned.has(n)) { warned.add(n); console.warn("legacy value missing:", n); } return v || {}; }',
       *[f'let {n} = {v};' for n, v in declare.items()],
       *stubs, code,
       'export const vars = {',
       *[f'  get {n}() {{ return {n}; }}, set {n}(v) {{ {n} = v; }},' for n in lets + list(declare)],
       '};',
       'export const api = { ' + ', '.join(fns + consts) + ', ' + ', '.join(f'get {n}() {{ return {n}; }}' for n in lets) + ' };', '']
(OUT / 'render.js').write_text('\n'.join(out), encoding='utf-8')
(OUT / 'render.d.ts').write_text('// GENERATED: the vendored renderer, untyped.\nexport const hooks: Record<string, any>;\nexport const vars: Record<string, any>;\nexport const api: Record<string, any>;\n', encoding='utf-8')
(OUT / 'spr3d.js').write_text('// GENERATED by tools/legacy-render/extract.py: the prototype sprite generator, unchanged.\n// @ts-nocheck\nexport const SOURCE = ' + json.dumps(GERADOR) + ';\n', encoding='utf-8')
style = HEAD[HEAD.find('<style>') + 7:HEAD.find('</style>')]
body = HEAD[HEAD.find('</style>') + 8:]
(OUT / 'prototype.css').write_text('/* GENERATED from the prototype: its stylesheet, unchanged. */\n' + style, encoding='utf-8')
(OUT / 'body.html').write_text(body.strip() + '\n', encoding='utf-8')
print(f'{len(spans)} spans, {len(code)} chars; {len(missing)} hooks: {" ".join(missing)}')
