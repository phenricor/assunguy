import { readFileSync } from 'node:fs';
import { VEHICLES, TRANSPORT_ROLES } from '@assunguy/data';
import { computeEconomy, generateWorld, railExits, vehicleAvailable, raceTime, type GameState, type LotKey } from '@assunguy/sim';
const d = JSON.parse(readFileSync(process.argv[2] as string, 'utf8'));
const s = d.s as GameState, w = generateWorld(s.seed, s.mapVersion);
console.log('t', s.market.t, 'raceTime', raceTime(s), 'level', s.level, 'cash', Math.round(s.cash));
const tr = Object.entries(s.map.buildings).filter(([, t]) => (TRANSPORT_ROLES as any)[t]);
for (const [k, t] of tr) console.log(k, t, JSON.stringify(s.fleet[k as LotKey] ?? {}), 'lvl', s.upgrades[k as LotKey] ?? 0, t === 'trainStation' ? JSON.stringify(railExits(s, k as LotKey)) : '');
console.log('avail', JSON.stringify(Object.keys(VEHICLES).map((v) => [v, vehicleAvailable(s, v as never), (VEHICLES as any)[v].lateGame ?? false, (VEHICLES as any)[v].minLevel ?? 1])));
const c = computeEconomy(s, w);
console.log('comp', JSON.stringify(c.transport.competitiveness));
for (const g of c.transport.gateways as any[]) console.log('gw', g.key, g.type, Math.round(g.capacity), JSON.stringify(g.dests?.map((x: any) => [x.d, +x.full.toFixed(2)])));
